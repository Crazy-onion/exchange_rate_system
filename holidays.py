def is_holiday(d):
    """判断是否为假期(周末或公众假期)"""
    if isinstance(d, str):
        d = date.fromisoformat(d)
    if d.weekday() >= 5:  # 周六周日
        return True
    if d in ALL_HOLIDAYS:
        return True
    return False


def is_workday(d):
    """判断是否为工作日"""
    return not is_holiday(d)


def get_last_workday_of_month(year, month):
    """获取当月最后一个工作日"""
    if month == 12:
        next_month = date(year + 1, 1, 1)
    else:
        next_month = date(year, month + 1, 1)
    d = next_month - timedelta(days=1)
    while is_holiday(d):
        d -= timedelta(days=1)
    return d


def get_first_workday_of_month(year, month):
    """获取当月第一个工作日(如果1号是假期，取上月最后一个工作日)"""
    d = date(year, month, 1)
    if is_holiday(d):
        # 月初遇假期，取上个月最后一个工作日
        if month == 1:
            d = date(year - 1, 12, 31)
        else:
            d = date(year, month, 1) - timedelta(days=1)
        while is_holiday(d):
            d -= timedelta(days=1)
    return d
